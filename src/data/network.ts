export const stationList = Object.values(stations).filter(
  (s, i, arr) => arr.findIndex((x) => x.x === s.x && s.y === x.y && x.name === s.name) === i || s.id !== 'estacion_central',
);

/** Estaciones únicas por id (sin el alias duplicado de plaza) */
export function getUniqueStations(): Station[] {
  const seen = new Set<string>();
  const result: Station[] = [];
  for (const s of Object.values(stations)) {
    const key = `${s.x},${s.y}`;
    if (seen.has(key)) continue;
    seen.add(key);
    result.push(s);
  }
  return result;
}

export function getStation(id: string): Station | undefined {
  return stations[id];
}

export function getLinesForStation(stationId: string): TransitLine[] {
  return lines.filter((l) => l.stationIds.includes(stationId));
}

export function getLinePath(line: TransitLine): { x: number; y: number }[] {
  return line.stationIds
    .map((id) => stations[id])
    .filter(Boolean)
    .map((s) => ({ x: s.x, y: s.y }));
}
