export function elementItemId(symbol) {
  return `el-${symbol.toLowerCase()}`;
}

export function researchForElement(el) {
  if (el.z <= 20 && !el.radioactive) return el.abundance === "common" ? "start" : "chemistry";
  if (el.category === "lanthanide") return "rare-earths";
  if (el.category === "actinide" || el.z >= 84) return "nuclear";
  if (el.category === "noble") return "noble-gases";
  if (el.category === "halogen") return el.z <= 17 ? "chemistry" : "advanced-chemistry";
  if (el.abundance === "common") return "start";
  if (el.abundance === "uncommon") return "metallurgy";
  if (el.abundance === "rare") return "advanced-metals";
  return "frontier";
}
