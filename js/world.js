  function country(cc) {
    if (!cc) return DEFAULT;
    return COUNTRIES[String(cc).toUpperCase()] || DEFAULT;
  }

  function inflationFactor(cc, year) {
    const c = country(cc);
    const years = Math.max(0, year - 2000);
    return Math.pow(1 + (c.infl || 0.03), years);
  }

  function priceLevel(cc, year) {
    const c = country(cc);
    return (c.gdppc / 15500) * inflationFactor(cc, year);
  }

  function tzOffset(cc, lon) {
    const c = country(cc);
    const wide = ["US", "RU", "CA", "AU", "BR", "MX", "ID", "CN", "KZ", "MN", "CD", "AR", "CL"];
    if (wide.includes(c.iso) && Number.isFinite(lon)) {
      return Math.round(lon / 15);
    }
    return c.tz;
  }

  function nearestCity(lat, lon, maxKm = 80) {
    let best = null;
    let bestD = maxKm;
    for (const city of CITY_OBJS) {
      const d = U.haversineKm(lat, lon, city.lat, city.lon);
      if (d < bestD) {
        bestD = d;
        best = city;
      }
    }
    return best ? { ...best, distKm: bestD } : null;
  }

  function findCityByName(name, cc) {
    if (!name) return null;
    const n = name.toLowerCase();
    return (
      CITY_OBJS.find((c) => c.name.toLowerCase() === n && (!cc || c.cc === cc)) ||
      CITY_OBJS.find((c) => c.name.toLowerCase() === n) ||
      CITY_OBJS.find((c) => (cc ? c.cc === cc : false) && c.name.toLowerCase().includes(n)) ||
      null
    );
  }

  function estimatePopK(place) {
    const type = (place.settlementKind || place.type || place.osmValue || "").toLowerCase();
    const named = findCityByName(place.city, place.countryCode);
    if (named) return named.popK;
    if (type.includes("city") || type === "administrative") {
      const metro = nearestCity(place.lat, place.lon, 18);
      return metro ? metro.popK : 180;
    }
    if (type.includes("town")) return 28;
    if (type.includes("suburb") || type.includes("neighbourhood") || type.includes("quarter")) return 40;
    if (type.includes("village")) return 2.4;
    if (type.includes("hamlet") || type.includes("isolated") || type.includes("farm")) return 0.4;
    const nearby = nearestCity(place.lat, place.lon, 10);
    if (nearby) return nearby.popK;
    return 8;
  }

